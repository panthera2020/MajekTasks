/*
A sequence statement is a statement that consists of a sequence of statements executed in order. 
It is often used to group multiple statements together so that they can be treated as a  single statement.
*/

public class SequenceStatement {
    public static void main(String[] args) {
        // Example of a sequence statement
        int a = 5;
        int b = 10;
        int sum = a + b;
        System.out.println("The sum of " + a + " and " + b + " is: " + sum);
    }
}
